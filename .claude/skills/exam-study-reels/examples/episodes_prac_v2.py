EPS = copy.deepcopy(V1.EPS)
for n, ep in EPS.items():
    cta = [s for s in ep["scenes"] if s["type"] == "cta"][0]
    idx, say, cap = ANS[n]
    li = len(ep["lines"])
    ep["lines"].append(dict(say=say, cap=cap, pause=2.3))
    cta["lines"] = cta["lines"] + [li]
    cta["reveal"] = dict(line=li, answer=idx)

