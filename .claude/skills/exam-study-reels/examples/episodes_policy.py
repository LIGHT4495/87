def hook(i, h):
    return dict(type="hook", lines=[i], headline=h)


def exam(i, h, q, html, stamp, ok=False):
    return dict(type="exam", lines=[i], headline=h, tag=f"제24회 기출 응용 · 정책론 · {q}번", html=html,
                stamp=stamp, stamp_color=GRN if ok else RED, stamp_line=i, stamp_frac=0.85)


def cta(a, b, q, buttons, ans):
    return dict(type="cta", lines=[a, b], headline=CTA_HEAD, q=q, buttons=buttons, reveal=dict(line=b, answer=ans))


